<?php

namespace App\Console\Commands;

use App\Analytics\Support\DatacenterRanges;
use App\Analytics\Support\ReferrerSpam;
use Illuminate\Console\Command;
use Illuminate\Http\Client\Response;
use Illuminate\Support\Facades\Http;

/** Refreshes the lists behind bot filtering from their public sources. Run it before a release; the result ships with the release. */
class UpdateBotLists extends Command
{
    protected $signature = 'bots:update-lists';

    protected $description = 'Download the data center address ranges and the referrer spam list into resources/data';

    public function handle(): int
    {
        $cidrs = [];
        $sources = [
            'Amazon EC2' => ['https://ip-ranges.amazonaws.com/ip-ranges.json', fn ($j) => [
                ...array_column(array_filter($j['prefixes'] ?? [], fn ($p) => ($p['service'] ?? '') === 'EC2'), 'ip_prefix'),
                ...array_column(array_filter($j['ipv6_prefixes'] ?? [], fn ($p) => ($p['service'] ?? '') === 'EC2'), 'ipv6_prefix'),
            ]],
            'Google Cloud' => ['https://www.gstatic.com/ipranges/cloud.json', fn ($j) => array_map(fn ($p) => $p['ipv4Prefix'] ?? $p['ipv6Prefix'] ?? '', $j['prefixes'] ?? [])],
            'Oracle Cloud' => ['https://docs.oracle.com/en-us/iaas/tools/public_ip_ranges.json', fn ($j) => array_column(array_merge(...array_column($j['regions'] ?? [], 'cidrs')), 'cidr')],
            'DigitalOcean' => ['https://digitalocean.com/geo/google.csv', fn ($t) => self::csvPrefixes($t)],
            'Linode' => ['https://geoip.linode.com/', fn ($t) => self::csvPrefixes($t)],
        ];
        foreach ($sources as $name => [$url, $extract]) {
            $res = $this->download($url);
            if (! $res?->successful()) {
                $this->error("{$name}: could not download (".($res?->status() ?? 'no connection').'). Nothing was changed.');

                return self::FAILURE;
            }
            $found = array_values(array_filter($extract(str_ends_with($url, '.json') ? $res->json() : $res->body())));
            $this->line(sprintf('%-13s %s ranges', $name, number_format(count($found))));
            $cidrs = [...$cidrs, ...$found];
        }
        $data = DatacenterRanges::build($cidrs);
        file_put_contents(DatacenterRanges::path(), "<?php\n\n// Generated by `php artisan bots:update-lists`. Do not edit.\nreturn ".var_export($data, true).";\n");
        $this->info(sprintf('Wrote %s IPv4 and %s IPv6 ranges.', number_format(count($data['v4'])), number_format(count($data['v6']))));

        $res = $this->download('https://raw.githubusercontent.com/matomo-org/referrer-spam-list/master/spammers.txt');
        if (! $res?->successful()) {
            $this->error('Referrer spam list: could not download ('.($res?->status() ?? 'no connection').').');

            return self::FAILURE;
        }
        $domains = array_flip(array_values(array_filter(array_map(fn ($l) => strtolower(trim($l)), explode("\n", $res->body())), fn ($l) => $l !== '' && $l[0] !== '#' && str_contains($l, '.'))));
        file_put_contents(ReferrerSpam::path(), "<?php\n\n// Generated by `php artisan bots:update-lists` from the public-domain Matomo referrer spam list. Do not edit.\nreturn ".var_export(array_map(fn () => 1, $domains), true).";\n");
        $this->info(sprintf('Wrote %s spam domains.', number_format(count($domains))));

        return self::SUCCESS;
    }

    private function download(string $url): ?Response
    {
        try {
            return Http::timeout(60)->retry(2, 2000, throw: false)->get($url);
        } catch (\Throwable) {
            return null;
        }
    }

    /** The first column of a geofeed (`prefix,country,…`), skipping comments. */
    private static function csvPrefixes(string $text): array
    {
        $out = [];
        foreach (explode("\n", $text) as $line) {
            $line = trim($line);
            if ($line !== '' && $line[0] !== '#') {
                $out[] = explode(',', $line)[0];
            }
        }

        return $out;
    }
}
