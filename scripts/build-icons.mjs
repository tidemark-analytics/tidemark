#!/usr/bin/env node
// Builds public/assets/icons.svg — a single SVG sprite containing only the Lucide icons listed in scripts/icons.txt.
// Dev-time only (the app itself needs no Node):
//   npm i --no-save lucide-static && node scripts/build-icons.mjs
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = [process.argv[2], join(root, 'node_modules/lucide-static/icons')].filter(Boolean).find((p) => existsSync(p));
if (!src) { console.error('lucide-static not found. Run: npm i --no-save lucide-static'); process.exit(1); }

const names = readFileSync(join(root, 'scripts/icons.txt'), 'utf8').split('\n').map((l) => l.trim()).filter((l) => l && !l.startsWith('#'));
const symbols = names.map((name) => {
  const file = join(src, `${name}.svg`);
  if (!existsSync(file)) throw new Error(`Unknown Lucide icon: ${name}`);
  const body = readFileSync(file, 'utf8').replace(/<!--[\s\S]*?-->/g, '').replace(/<svg[^>]*>/, '').replace('</svg>', '').trim().replace(/\n\s*/g, '');
  return `  <symbol id="${name}" viewBox="0 0 24 24">${body}</symbol>`;
});
const out = `<svg xmlns="http://www.w3.org/2000/svg" style="display:none">\n<!-- Lucide icons (ISC License, https://lucide.dev). Generated by scripts/build-icons.mjs — do not edit. -->\n${symbols.join('\n')}\n</svg>\n`;
writeFileSync(join(root, 'public/assets/icons.svg'), out);
console.log(`icons.svg: ${names.length} icons, ${(out.length / 1024).toFixed(1)} KB`);
